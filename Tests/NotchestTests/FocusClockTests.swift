import XCTest
@testable import Notchest

final class FocusClockTests: XCTestCase {
    func testElapsedTimeUsesDeadlineInsteadOfTickCount() {
        var clock = FocusClock()
        let start = Date(timeIntervalSince1970: 1_000)
        clock.start(at: start)
        XCTAssertEqual(clock.remaining(at: start.addingTimeInterval(600)), 900, accuracy: 0.001)
        XCTAssertEqual(clock.remaining(at: start.addingTimeInterval(1_600)), 0)
    }

    func testPauseAndResumeKeepRemainingTime() {
        var clock = FocusClock()
        let start = Date(timeIntervalSince1970: 1_000)
        clock.start(at: start)
        clock.pause(at: start.addingTimeInterval(120))
        XCTAssertEqual(clock.remaining(at: start.addingTimeInterval(10_000)), 1_380)
        clock.start(at: start.addingTimeInterval(10_000))
        XCTAssertEqual(clock.remaining(at: start.addingTimeInterval(10_060)), 1_320)
    }

    func testRestoredDeadlineCompletesExactlyOnce() throws {
        var original = FocusClock()
        let start = Date(timeIntervalSince1970: 1_000)
        original.start(at: start)
        var restored = try JSONDecoder().decode(FocusClock.self, from: JSONEncoder().encode(original))
        XCTAssertFalse(restored.finishIfNeeded(at: start.addingTimeInterval(1499)))
        XCTAssertTrue(restored.finishIfNeeded(at: start.addingTimeInterval(1500)))
        XCTAssertFalse(restored.finishIfNeeded(at: start.addingTimeInterval(1600)))
        XCTAssertEqual(restored.remaining(at: start.addingTimeInterval(1600)), 0)
    }

    func testResetCancelsRunningDeadlineAndChangesDuration() {
        var clock = FocusClock()
        clock.start(at: Date())
        clock.reset(minutes: 5)
        XCTAssertFalse(clock.isRunning)
        XCTAssertEqual(clock.duration, 300)
        XCTAssertEqual(clock.pausedRemaining, 300)
    }

    func testRestartAfterCompletionUsesFullDuration() {
        var clock = FocusClock()
        let start = Date(timeIntervalSince1970: 1_000)
        clock.start(at: start)
        clock.finishIfNeeded(at: start.addingTimeInterval(1500))
        clock.start(at: start.addingTimeInterval(2000))
        XCTAssertEqual(clock.remaining(at: start.addingTimeInterval(2000)), 1500)
    }

    func testClipboardRejectsConfidentialTransientAndGeneratedData() async {
        await MainActor.run {
            for excluded in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
                XCTAssertFalse(AppModel.mayRecordClipboard(types: ["public.utf8-plain-text", excluded]))
            }
            XCTAssertTrue(AppModel.mayRecordClipboard(types: ["public.utf8-plain-text"]))
        }
    }

    func testNotesLanguageAndTimerSurviveModelRelaunch() async throws {
        try await MainActor.run {
            let suite = "dev.notchest.tests.\(UUID().uuidString)"
            let defaults = try XCTUnwrap(UserDefaults(suiteName: suite))
            defer { defaults.removePersistentDomain(forName: suite) }
            let first = AppModel(defaults: defaults, startServices: false)
            XCTAssertFalse(first.clipboardEnabled)
            first.note = "فكرة تجريبية"
            first.arabic = false
            first.resetTimer(minutes: 50)
            first.toggleTimer()
            first.shutdown()
            let restored = AppModel(defaults: defaults, startServices: false)
            XCTAssertEqual(restored.note, "فكرة تجريبية")
            XCTAssertFalse(restored.arabic)
            XCTAssertTrue(restored.clock.isRunning)
            XCTAssertEqual(restored.clock.duration, 3000)
            restored.shutdown()
        }
    }
}
